"""Create a dictionary called phone with:
"brand" → "Apple"
"model" → "iPhone 17"
"color" → "Black"
"storage" → "256GB"

Then print three separate things:
all the keys using .keys()
all the values using .values()
all the key-value pairs using .items()"""

phone= {
    "brand" : "Apple",
    "model": "iPhone 17",
    "color" : "Black",
    "storage" : "256GB"
}
print(phone.keys())
print(phone.values())
print(phone.items())